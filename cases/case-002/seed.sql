--   2. 累積在庫がマイナスになるのは SX-400 の2時点だけ
--        2025-10-20 19:05:00 → -2 / 2026-01-20 19:50:00 → -3
--   3. 正規の記録は created_at = occurred_at（ハンディ端末がその場で登録する）
--   4. created_at > occurred_at になるのは相沢の遡及登録3件だけ
--   5. 棚卸し日と同日の movement は無い（前後の解釈が割れないように）
--
-- 検算は frontend/src/game/case-002.test.ts が毎回行う。
-- @see docs/cases/case-002.md
