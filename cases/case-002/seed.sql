-- 方針:
--   * 全行を明示的に書く。CASE 001 と違い、このCASEは**すべての行が算術に効く**。
--     棚卸しとの突き合わせ・マイナス在庫・遡及登録の3つが、どれも1行ずれると
--     判定が割れるため、ノイズ生成に混ぜられる行が1つも無い。
