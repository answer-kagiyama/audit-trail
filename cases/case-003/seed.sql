-- ----------------------------------------------------------------------------
-- doors: 扉
--
-- gate_type がこのCASEの鍵。
--   回転扉 … 1人ずつしか通れない。記録に漏れが無い
--   自動扉 … 前の人に続いて通れてしまう。記録が飛ぶことがある
-- ----------------------------------------------------------------------------
CREATE TABLE doors (
  id        INTEGER PRIMARY KEY,
  door_name TEXT    NOT NULL UNIQUE,
  building  TEXT    NOT NULL CHECK (building IN ('本館', '研究棟')),
  gate_type TEXT    NOT NULL CHECK (gate_type IN ('回転扉', '自動扉'))
);

