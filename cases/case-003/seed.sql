--   node tools/build-case-db.mjs cases/case-003
--
-- 方針:
--   * 全行を明示的に書く。このCASEは**記録の並びそのものが証拠**なので、
--     1行の増減で判定が割れる。生成で埋められる行が1つも無い。
--   * random() は使わない（ビルドのたびに .sqlite が変わり CI の差分検出が壊れる）。
--   * 日付の引き算をしない。時刻は ISO 形式の TEXT で、大小比較だけで解ける
--     （方言関数を必須にしないため。docs/cases/case-003.md §10）。
--
-- データが満たしている不変条件（docs/cases/case-003.md §11）:
--   1. C-1042 の in/out は **カードごと（3/3）でも、カード×扉ごと（2/2、1/1）でも
--      釣り合っている**。数を数えるどの切り口でも異常が出ない
--   2. 「直前の記録と同じ向き」になるのは、カード×扉で区切ったとき
--      C-1042 の 02:47 と 03:16 の2行だけ
--   3. カードだけで区切ると無関係な4枚が混ざる（扉で区切る必然性の道標）
--   4. 2026-06-13 02:47 に館内にいるのは久我山と早瀬の2名
--   5. 里見（01:55 退館）と阿久津（03:30 入館）が区間の端のノイズになる
--   6. 有効なカードを2枚以上持つのは森本だけ
--   7. 久我山は**研究棟の扉に自分のカードの記録が1件も無い**
--
-- 検算は frontend/src/game/case-003.test.ts が毎回行う。
-- @see docs/cases/case-003.md
-- ============================================================================

