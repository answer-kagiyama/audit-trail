-- ----------------------------------------------------------------------------
-- cards: 入退館カード
--
-- 1人が複数枚を持ちうる。紛失や破損で再発行されるため。
-- 正しく運用されていれば、古い方に revoked_on が入る——里見がその例。
-- 森本の C-1042 はそれが入っていない。ここが事件の入口になる。
-- ----------------------------------------------------------------------------
CREATE TABLE cards (
  id          INTEGER PRIMARY KEY,
  card_number TEXT    NOT NULL UNIQUE,
  holder_id   INTEGER NOT NULL REFERENCES staff(id),
  issued_on   TEXT    NOT NULL,
  revoked_on  TEXT
);

